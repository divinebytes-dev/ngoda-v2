CREATE OR REPLACE FUNCTION public.open_my_next_fiscal_year()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
    v_user public.users%rowtype;

    v_current_fiscal_year integer;
    v_next_fiscal_year integer;

    v_current_period_count integer;
    v_created_period_count integer;
BEGIN
    /*
     * Authentication
     */
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION USING
            ERRCODE = '42501',
            MESSAGE = 'UNAUTHENTICATED';
    END IF;

    /*
     * Authorization
     *
     * Only Finance can open a fiscal year.
     */
    IF NOT public.has_role(
        ARRAY[
            'finance'
        ]::text[]
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = '42501',
            MESSAGE = 'FORBIDDEN';
    END IF;

    /*
     * Fetch authenticated application user.
     */
    SELECT user_record.*
    INTO v_user
    FROM public.fetch_user_by_id(
        auth.uid()::text
    ) AS user_record;

    IF v_user.id IS NULL THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'USER_NOT_FOUND';
    END IF;

    IF v_user.country_code IS NULL
       OR btrim(v_user.country_code) = '' THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'USER_COUNTRY_NOT_CONFIGURED';
    END IF;

    /*
     * Determine the current fiscal year from the
     * configured period containing the current time.
     */
    SELECT fpc.fiscal_year
    INTO v_current_fiscal_year
    FROM public.fiscal_period_config AS fpc
    WHERE fpc.country_code = v_user.country_code
      AND CURRENT_TIMESTAMP >= fpc.opening_date
      AND CURRENT_TIMESTAMP <= fpc.closing_date
    ORDER BY
        fpc.fiscal_year DESC,
        fpc.period DESC
    LIMIT 1;

    IF v_current_fiscal_year IS NULL THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CURRENT_FISCAL_YEAR_NOT_CONFIGURED';
    END IF;

    v_next_fiscal_year :=
        v_current_fiscal_year + 1;

    /*
     * Make sure the source fiscal year actually
     * contains periods.
     */
    SELECT COUNT(*)
    INTO v_current_period_count
    FROM public.fiscal_period_config AS fpc
    WHERE fpc.country_code = v_user.country_code
      AND fpc.fiscal_year = v_current_fiscal_year;

    IF v_current_period_count = 0 THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'CURRENT_FISCAL_YEAR_HAS_NO_PERIODS';
    END IF;

    /*
     * Do not create the next fiscal year if any
     * configuration already exists for it.
     */
    IF EXISTS (
        SELECT 1
        FROM public.fiscal_period_config AS fpc
        WHERE fpc.country_code = v_user.country_code
          AND fpc.fiscal_year = v_next_fiscal_year
    ) THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'NEXT_FISCAL_YEAR_ALREADY_CONFIGURED';
    END IF;

    /*
     * Copy the current fiscal-year configuration
     * into the next fiscal year.
     *
     * New periods start OPEN.
     *
     * UUID/id is not copied and should therefore be
     * generated by the fiscal_period_config.id default.
     */
    INSERT INTO public.fiscal_period_config (
        fiscal_year,
        period,
        country_code,
        period_name,
        opening_date,
        closing_date,
        is_closed,
        created_at,
        created_by,
        updated_at,
        updated_by
    )
    SELECT
        v_next_fiscal_year,
        fpc.period,
        fpc.country_code,
        fpc.period_name,
        fpc.opening_date + INTERVAL '1 year',
        fpc.closing_date + INTERVAL '1 year',
        false,
        CURRENT_TIMESTAMP,
        auth.uid()::text,
        CURRENT_TIMESTAMP,
        NULL
    FROM public.fiscal_period_config AS fpc
    WHERE fpc.country_code = v_user.country_code
      AND fpc.fiscal_year = v_current_fiscal_year
    ORDER BY fpc.period;

    GET DIAGNOSTICS
        v_created_period_count = ROW_COUNT;

    /*
     * Safety check.
     *
     * The copied fiscal year should contain exactly
     * the same number of periods as the source year.
     *
     * Raising an exception here rolls back the INSERT.
     */
    IF v_created_period_count <> v_current_period_count THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'FISCAL_YEAR_PERIOD_COPY_INCOMPLETE';
    END IF;

    RETURN jsonb_build_object(
        'country_code',
        v_user.country_code,
        'source_fiscal_year',
        v_current_fiscal_year,
        'opened_fiscal_year',
        v_next_fiscal_year,
        'periods_created',
        v_created_period_count
    );
END;
$function$;